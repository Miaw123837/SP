const ITEMS_PER_PAGE = 24;
let currentPage = 1;
let currentFilter = allPhones;

function initSidebar() {
  const brands = ["All", ...new Set(allPhones.map((p) => p.brand))].sort();
  document.getElementById("brandList").innerHTML = brands
    .map((b) => {
      const count = allPhones.filter((p) => p.brand === b).length;
      return `<button onclick="filterByBrand('${b}')" class="text-left px-4 py-2 hover:bg-red-50 hover:text-red-600 transition block w-full border-b border-gray-100 flex justify-between items-center group">
                    <span class="${b === "All" ? "font-bold" : ""}">${b === "All" ? "SEMUA MEREK" : b}</span> 
                    <span class="text-gray-400 text-[10px] bg-gray-100 px-2 py-0.5 rounded-full">${b === "All" ? allPhones.length : count}</span>
                </button>`;
    })
    .join("");
}

function filterByBrand(brand) {
  currentPage = 1;
  currentFilter =
    brand === "All" ? allPhones : allPhones.filter((p) => p.brand === brand);
  document.getElementById("pageTitle").innerText =
    brand === "All" ? "DAFTAR PONSEL" : `HP ${brand.toUpperCase()}`;
  renderGrid();
}

document.getElementById("searchInput").addEventListener("input", (e) => {
  const q = e.target.value.toLowerCase();
  currentFilter = allPhones.filter(
    (p) =>
      p.model.toLowerCase().includes(q) || p.brand.toLowerCase().includes(q),
  );
  currentPage = 1;
  renderGrid();
});

function renderGrid() {
  const grid = document.getElementById("phoneGrid");
  const totalLabel = document.getElementById("totalCount");
  const pagination = document.getElementById("paginationContainer");

  const start = (currentPage - 1) * ITEMS_PER_PAGE;
  const pageData = currentFilter.slice(start, start + ITEMS_PER_PAGE);
  const totalPages = Math.ceil(currentFilter.length / ITEMS_PER_PAGE);

  totalLabel.innerText = `${currentFilter.length} Perangkat`;

  if (currentFilter.length === 0) {
    grid.innerHTML = `<div class="col-span-full text-center py-20 text-gray-400">Tidak ada hasil ditemukan.</div>`;
    pagination.innerHTML = "";
    return;
  }

  grid.innerHTML = pageData
    .map(
      (phone) => `
                <div class="phone-card p-3 flex flex-col items-center cursor-pointer group rounded-sm" onclick="openModal(${phone.id})">
                    <div class="phone-img-container mb-2">
                        <img src="${getPhoneImg(phone.brand, phone.model)}" alt="${phone.model}" class="phone-img" 
                             onerror="this.style.display='none'; this.nextElementSibling.style.display='block';">
                        <i class="fas fa-mobile-alt text-6xl text-gray-200 mt-10"></i>
                    </div>
                    <div class="w-full text-center mt-2">
                        <div class="text-[10px] text-red-700 font-bold uppercase mb-1 opacity-70">${phone.brand}</div>
                        <h4 class="font-bold text-sm text-gray-900 leading-tight mb-2 group-hover:text-red-700">${phone.model}</h4>
                        <div class="text-[10px] text-gray-500 space-y-1 text-left border-t border-gray-100 pt-2">
                            <div class="truncate"><i class="fas fa-microchip w-3 text-red-700"></i> ${phone.chip}</div>
                            <div class="truncate"><i class="fas fa-battery-half w-3 text-red-700"></i> ${phone.battery}</div>
                        </div>
                    </div>
                </div>
            `,
    )
    .join("");

  let pagHTML = "";
  if (totalPages > 1) {
    for (let i = 1; i <= totalPages; i++) {
      pagHTML += `<button onclick="changePage(${i})" class="page-btn border border-gray-300 px-3 py-1 ${currentPage === i ? "active" : "bg-white"} text-xs font-bold">${i}</button>`;
    }
  }
  pagination.innerHTML = pagHTML;
}

function changePage(p) {
  currentPage = p;
  renderGrid();
  window.scrollTo({ top: 0 });
}

function openModal(id) {
  const p = allPhones.find((x) => x.id === id);
  if (!p) return;

  document.getElementById("modalTitle").innerText = `${p.brand} ${p.model}`;

  const img = document.getElementById("modalImg");
  const icon = document.getElementById("modalIcon");

  img.style.display = "block";
  icon.style.display = "none";
  img.src = getPhoneImg(p.brand, p.model);

  img.onerror = function () {
    this.style.display = "none";
    icon.style.display = "block";
  };

  document.getElementById("modalRelease").innerText = p.release;
  document.getElementById("modalWeight").innerText = p.dim;
  document.getElementById("modalOS").innerText = p.os;
  document.getElementById("modalStorage").innerText = p.memory;

  const tb = document.getElementById("specsTableBody");
  const row = (l, v) =>
    `<tr><td class="spec-header text-right pr-3 font-semibold text-gray-600 bg-gray-50 border-r border-gray-200">${l}</td><td class="text-gray-800">${v}</td></tr>`;
  const head = (t) =>
    `<tr><td colspan="2" class="spec-category">${t}</td></tr>`;

  tb.innerHTML = `
                ${head("Informasi Utama")}
                ${row("Merek", p.brand)}
                ${row("Model", p.model)}
                ${row("Rilis", p.release)}
                ${head("Layar & Bodi")}
                ${row("Tipe Layar", p.screen)}
                ${row("Dimensi/Berat", p.dim)}
                ${head("Platform")}
                ${row("Chipset", p.chip)}
                ${row("Memori", p.memory)}
                ${row("Sistem Operasi", p.os)}
                ${head("Kamera")}
                ${row("Kamera Belakang", p.main_cam)}
                ${row("Kamera Depan", p.selfie_cam)}
                ${head("Lainnya")}
                ${row("Baterai", p.battery)}
                ${row("Konektivitas", p.comms)}
                ${row("Sensor", p.sensors)}
            `;

  document.getElementById("detailModal").classList.remove("hidden");
  document.body.style.overflow = "hidden";
}

function closeModal() {
  document.getElementById("detailModal").classList.add("hidden");
  document.body.style.overflow = "auto";
}

document.getElementById("detailModal").addEventListener("click", (e) => {
  if (e.target.id === "detailModal") closeModal();
});

